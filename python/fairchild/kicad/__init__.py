"""Live KiCad schematic → fairchild, over the KiCad IPC API (10.99+ / KiCad 11).

No export step, no toolbar button, no file watching: the REPL dials KiCad's
socket and pulls the netlist out of the *open* document.

    $ .venv/bin/python -i -m fairchild.kicad
    >>> sch                     # LiveSchematic, already connected
    >>> print(sch.report())
    >>> ckt = sch.circuit()     # fairchild.Circuit, deck already loaded
    >>> sch.refresh()           # re-pull after editing in KiCad

Requires `enable_server: true` in kicad_common.json (Preferences → Plugins →
Enable IPC API) and protos generated by ./regen_protos.sh from the same KiCad
source commit you are running.

Two seams worth knowing about, both verified against KiCad 10.99.0-1080:

* **Nets carry item KIIDs, not pin references.** `GetItemsById` will not
  resolve a pin KIID (it silently drops them and returns only the wires), so
  the net → (symbol, pin) join has to go the other way: every pin KIID from
  `GetItems(KOT_SCH_SYMBOL)` → `definition.items` appears in exactly one net.
  `PackSymbol` builds those from `GetPins(&aPath)`, so they are per-instance
  and per-sheet.

* **Per-instance SYMBOL field overrides are invisible over IPC.**
  `SCH_SYMBOL::Serialize` fills `definition.items` fields from `m_part` — the
  *library* symbol — and the proto has no instance field collection at all
  (only the 5 mandatory fields). So an instance that overrides `Sim.Params`
  reports the library default over IPC, silently. We read fields from the
  saved `.kicad_sch` instead and warn when the two disagree; see
  `Symbol.params_source`.

  Per-instance *sheet* fields need no workaround: `SheetSymbol.user_fields`
  does come over IPC, per instance, and is how a hierarchical sheet takes
  parameters — a symbol inside writes `l_m=${RING_HALF_LENGTH}` and each
  instance supplies its own value. That is the mechanism to reach for.

* **Whole-hierarchy reads need `sheet_path` cleared; joins need it kept.**
  `GetOpenDocuments` returns a specifier whose `sheet_path` is present but
  empty, which `api_handler_sch.cpp` reads as "filter to this sheet" and
  resolves to the root — 317 symbols instead of 1189 on a 91-sheet design,
  silently and with every pin resolving. Clear it to walk `Hierarchy()`. But a
  reused sheet is one `SCH_SYMBOL` packed once per path, so symbol and pin
  KIIDs repeat across instances and only `(sheet path, KIID)` is unique.
  `SheetSymbol.path` is the *container's* path, so an instance path is
  `path + (own id)`.
"""
