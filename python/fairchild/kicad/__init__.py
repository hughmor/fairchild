# Model node order per SPICE primitive, used to invert Sim.Pins. Sim.Pins is
# written `<symbolPinNumber>=<modelPinName>` (sim_model_serializer.cpp:274) so
# it maps symbol→model; emitting needs model→symbol, in the model's own order.
# ponytail: two-terminal only. Q/M name their nodes (C/B/E, D/G/S/B) and would
# need their own rows; until one shows up we fall back to pin-number order and
# say so rather than guessing a transposition.
_MODEL_NODE_ORDER = {
    "R": ("+", "-"), "L": ("+", "-"), "C": ("+", "-"),
    "V": ("+", "-"), "I": ("+", "-"), "D": ("+", "-"),
}

# Reference-designator prefix → primitive, for symbols with no Sim.Device.
# KiCad leaves it off passives (Device:R_US carries no Sim.Device at all) and
# infers the model from the refdes, so we have to as well.
_REFDES_PRIMITIVE = {"R": "R", "L": "L", "C": "C", "V": "V", "I": "I", "D": "D"}

_SUBST_RE = re.compile(r"\$\{([^}]+)\}")

# KiCad Sim.Params name → position in the fairchild/SPICE waveform argument
# list. fairchild parses SIN(vo va freq td theta phase) — waveforms.rs:69.
