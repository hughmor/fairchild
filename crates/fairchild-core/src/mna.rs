fn index_circuit(netlist: &Netlist) -> (IndexMap<String, usize>, IndexMap<String, usize>) {
    let mut node_index: IndexMap<String, usize> = IndexMap::new();
    let mut vsrc_index: IndexMap<String, usize> = IndexMap::new();

    for el in &netlist.elements {
        match el {
            Element::Resistor { pos, neg, .. }
            | Element::Capacitor { pos, neg, .. }
            | Element::Inductor { pos, neg, .. }
            | Element::CurrentSource { pos, neg, .. } => {
                add_node(&mut node_index, pos);
                add_node(&mut node_index, neg);
            }
            Element::Diode { anode, cathode, .. } => {
                add_node(&mut node_index, anode);
                add_node(&mut node_index, cathode);
            }
            Element::Mosfet {
                drain,
                gate,
                source,
                bulk,
                ..
            } => {
                add_node(&mut node_index, drain);
                add_node(&mut node_index, gate);
                add_node(&mut node_index, source);
                add_node(&mut node_index, bulk);
            }
            Element::Bjt {
                collector,
                base,
                emitter,
                substrate,
                ..
            } => {
                add_node(&mut node_index, collector);
                add_node(&mut node_index, base);
                add_node(&mut node_index, emitter);
                add_node(&mut node_index, substrate);
            }
            Element::VoltageSource { name, pos, neg, .. } => {
                add_node(&mut node_index, pos);
                add_node(&mut node_index, neg);
                let n = vsrc_index.len();
                vsrc_index.entry(name.clone()).or_insert(n);
            }
            Element::XOsdi { nets, .. } => {
                for net in nets {
                    add_node(&mut node_index, net);
                }
            }
            Element::Behavioral {
                name,
                pos,
                neg,
                kind,
                ..
            } => {
                add_node(&mut node_index, pos);
                add_node(&mut node_index, neg);
                if *kind == fairchild_parser::BehavioralKind::Voltage {
                    let n = vsrc_index.len();
                    vsrc_index.entry(name.clone()).or_insert(n);
                }
            }
            Element::CoupledInductors { .. } => {
                // No new nodes — L1 and L2 terminals already registered by their
                // Inductor elements.
            }
            Element::VoltageSwitch {
                pos,
                neg,
                ctrl_pos,
                ctrl_neg,
                ..
            } => {
                add_node(&mut node_index, pos);
                add_node(&mut node_index, neg);
                add_node(&mut node_index, ctrl_pos);
                add_node(&mut node_index, ctrl_neg);
            }
            Element::CurrentSwitch { pos, neg, .. } => {
                // The control is a voltage source's branch row, which that
                // source already registered — no node of its own.
                add_node(&mut node_index, pos);
                add_node(&mut node_index, neg);
            }
            Element::TransmissionLine {
                a_pos,
                a_neg,
                b_pos,
                b_neg,
                ..
            } => {
                add_node(&mut node_index, a_pos);
                add_node(&mut node_index, a_neg);
                add_node(&mut node_index, b_pos);
                add_node(&mut node_index, b_neg);
                // The two branch-current rows are device extra nodes, allocated
                // by build_devices via num_extra_nodes/bind_extra_nodes.
            }
        }
    }

    (node_index, vsrc_index)
}

fn add_node(map: &mut IndexMap<String, usize>, node: &str) {
    if node != "0" {
        let n = map.len();
        map.entry(node.to_string()).or_insert(n);
    }
}

/// Backward Euler companion state for a capacitor at one time step.
/// Returns (G_eq, I_hist) where G_eq = C/h and I_hist = G_eq * V_prev.
pub fn cap_companion(capacitance: f64, h: f64, v_prev: f64) -> (f64, f64) {
    let g = capacitance / h;
    (g, g * v_prev)
}

/// Backward Euler companion state for an inductor at one time step.
/// Returns (G_eq, I_hist) where G_eq = h/L and I_hist = I_L_prev.
pub fn ind_companion(inductance: f64, h: f64, i_prev: f64) -> (f64, f64) {
    let g = h / inductance;
    (g, i_prev)
}

/// Trapezoidal Rule (TR) companion initial state for a capacitor.
/// G_eq = 2C/h.  I_hist = G_eq * V_prev (assumes I_C(0) = 0 at DC OP).
pub fn cap_companion_tr(capacitance: f64, h: f64, v_prev: f64) -> (f64, f64) {
    let g = 2.0 * capacitance / h;
    (g, g * v_prev)
}

/// Advance the TR capacitor companion after a solved timestep.
///
/// Given the stored state `(G_eq, I_hist_old)` and the new capacitor voltage `v_c_new`,
/// returns the companion for the *next* step.
/// Derivation: I_hist_new = 2·G_eq·V_C_new − I_hist_old.
pub fn cap_companion_tr_advance(g_eq: f64, i_hist_old: f64, v_c_new: f64) -> (f64, f64) {
    (g_eq, 2.0 * g_eq * v_c_new - i_hist_old)
}

/// Transition a capacitor companion from BE→TR after the first BE step.
///
/// The BE companion `(g_eq_be, i_hist_be)` encodes G_be = C/h, I_hist_be = C/h·V_C_prev.
/// After solving for v_c_new, the capacitor current was I_C = G_be·V_C_new − I_hist_be.
/// Returns the TR companion for the *next* step with G_eq = 2·G_be.
pub fn cap_companion_be_to_tr(g_eq_be: f64, i_hist_be: f64, v_c_new: f64) -> (f64, f64) {
    let i_c = g_eq_be * v_c_new - i_hist_be;
    let g_eq_tr = 2.0 * g_eq_be;
    (g_eq_tr, g_eq_tr * v_c_new + i_c)
}

/// Trapezoidal Rule companion initial state for an inductor.
/// G_eq = h/(2L).  I_hist = I_L_prev (= 0 when starting from DC OP).
pub fn ind_companion_tr(inductance: f64, h: f64, i_prev: f64) -> (f64, f64) {
    let g = h / (2.0 * inductance);
    (g, i_prev)
}

/// Advance the TR inductor companion after a solved timestep.
///
/// Given the stored state `(G_eq, I_hist_old)` and new inductor voltage `v_l_new`,
/// returns the companion for the next step.
/// Derivation: I_hist_new = 2·G_eq·V_L_new + I_hist_old.
pub fn ind_companion_tr_advance(g_eq: f64, i_hist_old: f64, v_l_new: f64) -> (f64, f64) {
    (g_eq, 2.0 * g_eq * v_l_new + i_hist_old)
}

/// Transition an inductor companion from BE→TR after the first BE step.
///
/// The inductor current during the BE step was I_L = G_be·V_L_new + I_hist_be.
/// Returns the TR companion for the next step with G_eq = G_be/2.
pub fn ind_companion_be_to_tr(g_eq_be: f64, i_hist_be: f64, v_l_new: f64) -> (f64, f64) {
    let i_l = g_eq_be * v_l_new + i_hist_be;
    let g_eq_tr = g_eq_be / 2.0;
    (g_eq_tr, i_l + g_eq_tr * v_l_new)
}

/// GEAR / BDF-2 companion for a capacitor with non-uniform step.
///
/// Two-step BDF: \dot{v}_{n+1} ≈ α·v_{n+1} − β₁·v_n + β₂·v_{n-1}
/// with ρ = h_n / h_{n-1}, α = (1+2ρ)/(h(1+ρ)), β₁ = (1+ρ)/h, β₂ = ρ²/(h(1+ρ)).
///
/// Returns the Norton (G_eq, I_hist) such that i_C = G_eq·v − I_hist.
pub fn cap_companion_gear2(
    capacitance: f64,
    h: f64,
    h_prev: f64,
    v_prev: f64,
    v_prev2: f64,
) -> (f64, f64) {
    let rho = h / h_prev;
    let denom = h * (1.0 + rho);
    let g_eq = capacitance * (1.0 + 2.0 * rho) / denom;
    let i_hist = capacitance * ((1.0 + rho) / h * v_prev - (rho * rho) / denom * v_prev2);
    (g_eq, i_hist)
}

/// GEAR / BDF-2 companion for an inductor with non-uniform step.
///
/// For v_L = L·di/dt, the BDF-2 Norton form is:
///   i_{n+1} = G_eq·v_{n+1} + I_hist
/// with G_eq = h(1+ρ)/(L(1+2ρ)),
///      I_hist = ((1+ρ)²/(1+2ρ))·i_n − (ρ²/(1+2ρ))·i_{n-1}.
pub fn ind_companion_gear2(
    inductance: f64,
    h: f64,
    h_prev: f64,
    i_prev: f64,
    i_prev2: f64,
) -> (f64, f64) {
    let rho = h / h_prev;
    let denom_a = 1.0 + 2.0 * rho;
    let g_eq = h * (1.0 + rho) / (inductance * denom_a);
    let i_hist = ((1.0 + rho).powi(2) / denom_a) * i_prev - (rho * rho / denom_a) * i_prev2;
    (g_eq, i_hist)
}

/// Look up the (pos, neg) terminal node names for a named inductor in the netlist.
///
/// Panics if the inductor is not found — only called when the K-element references
/// it, so the inductor is guaranteed to exist (the sanity check would have caught it).
fn find_inductor_terminals<'a>(
    netlist: &'a fairchild_parser::Netlist,
    name: &str,
) -> (&'a str, &'a str) {
    for el in &netlist.elements {
        if let Element::Inductor {
            name: n, pos, neg, ..
        } = el
        {
            if n == name {
                return (pos, neg);
            }
        }
    }
    panic!("coupled inductor '{name}' not found in netlist")
}

/// Stamp the mutual-conductance cross-coupling for a K element.
///
/// For coupled inductors the 2×2 companion system contributes off-diagonal
/// terms: G12 * (V_pos1 - V_neg1) drives current into nodes pos2/neg2, and
/// G12 * (V_pos2 - V_neg2) drives current into nodes pos1/neg1.
///
/// `g` is G12 (typically negative for positive coupling).
fn stamp_mutual_conductance(
    a: &mut [Vec<f64>],
    idx: &IndexMap<String, usize>,
    pos1: &str,
    neg1: &str,
    pos2: &str,
    neg2: &str,
    g: f64,
) {
    let p1 = idx.get(pos1).copied();
    let n1 = idx.get(neg1).copied();
    let p2 = idx.get(pos2).copied();
    let n2 = idx.get(neg2).copied();

    // L2 rows from L1 voltage: G12 * (V_pos1 - V_neg1) → current at pos2/neg2
    if let Some(r2) = p2 {
        if let Some(c1) = p1 {
            a[r2][c1] += g;
        }
        if let Some(c1) = n1 {
            a[r2][c1] -= g;
        }
    }
    if let Some(r2) = n2 {
        if let Some(c1) = p1 {
            a[r2][c1] -= g;
        }
        if let Some(c1) = n1 {
            a[r2][c1] += g;
        }
    }
    // L1 rows from L2 voltage: G12 * (V_pos2 - V_neg2) → current at pos1/neg1
    if let Some(r1) = p1 {
        if let Some(c2) = p2 {
            a[r1][c2] += g;
        }
        if let Some(c2) = n2 {
            a[r1][c2] -= g;
        }
    }
    if let Some(r1) = n1 {
        if let Some(c2) = p2 {
            a[r1][c2] -= g;
        }
        if let Some(c2) = n2 {
            a[r1][c2] += g;
        }
    }
}

/// Stamp a 2-terminal value (conductance, capacitance, or 1/L) between two MNA
/// rows identified by [`crate::device::NodeId`], into a raw row-major dense
/// matrix. Ground (`None`) terminals are skipped. This is the shared kernel for
/// both the netlist-element AC/noise stamps and the device small-signal
/// reactance stamps.
pub fn stamp_2port_by_id(
    mat: &mut [Vec<f64>],
    pos: crate::device::NodeId,
    neg: crate::device::NodeId,
    val: f64,
) {
    if let Some(p) = pos {
        mat[p][p] += val;
        if let Some(n) = neg {
            mat[p][n] -= val;
            mat[n][p] -= val;
        }
    }
    if let Some(n) = neg {
        mat[n][n] += val;
    }
}

/// Stamp a 2-terminal passive value (G or C) into a raw matrix, looking node
/// names up in `idx` (ground / unknown names resolve to `None` and are skipped).
/// Thin wrapper over [`stamp_2port_by_id`]; shared by `ac.rs` and `noise.rs`.
pub fn stamp_passive_2port(
    mat: &mut [Vec<f64>],
    idx: &IndexMap<String, usize>,
    pos: &str,
    neg: &str,
    val: f64,
) {
    stamp_2port_by_id(mat, idx.get(pos).copied(), idx.get(neg).copied(), val);
}

#[cfg(test)]
mod tests {
    use super::*;
    use fairchild_parser::parse_spice;

    #[test]
    fn voltage_divider_topology_size() {
        let net = parse_spice("* divider\nV1 in 0 1.0\nR1 in mid 1000\nR2 mid 0 1000\n.op\n.end\n")
            .unwrap();
        let topo = CircuitTopology::build(&net);
        // 2 nodes (in, mid) + 1 vsource = 3×3
        assert_eq!(topo.size, 3);
    }

    #[test]
    fn rc_circuit_topology() {
        let net = parse_spice("* RC\nV1 in 0 1.0\nR1 in out 1k\nC1 out 0 1u\n.op\n.end\n").unwrap();
        let topo = CircuitTopology::build(&net);
        // nodes: in, out (2) + 1 vsource = 3
        assert_eq!(topo.size, 3);
    }

    #[test]
    fn stamp_gmin_floors_node_and_internal_rows_but_skips_vsource() {
        // 2 nodes (in, mid) + 1 vsource (rows: [0,1]=nodes, [2]=vsrc aux) and
        // then a device-internal row appended at index 3.
        let net =
            parse_spice("* divider\nV1 in 0 1.0\nR1 in mid 1k\nR2 mid 0 1k\n.op\n.end\n").unwrap();
        let mut topo = CircuitTopology::build(&net);
        assert_eq!(topo.size, 3);
        let internal = topo.allocate_extra_rows(1); // index 3, a device-internal row
        assert_eq!(internal, 3);
        assert_eq!(topo.size, 4);

        let mut a = vec![vec![0.0; 4]; 4];
        topo.stamp_gmin(&mut a, 1e-12);

        // Node rows 0,1 get the floor; the vsource aux row 2 is skipped (clean
        // KCL diagonal); the device-internal row 3 gets the floor.
        assert_eq!(a[0][0], 1e-12);
        assert_eq!(a[1][1], 1e-12);
        assert_eq!(a[2][2], 0.0, "vsource branch row must NOT receive gmin");
        assert_eq!(a[3][3], 1e-12, "device-internal row must receive gmin");
        // Off-diagonals untouched.
        assert_eq!(a[0][1], 0.0);
    }
}
