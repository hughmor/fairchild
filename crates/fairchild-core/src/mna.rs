/// In-place version of [`stamp_netlist_scaled`].  `mat` is cleared and
/// then filled — the caller owns the allocation and reuses it across NR
/// iterations to avoid the N+1 heap allocations per stamp.
pub fn stamp_netlist_scaled_in_place(
    mat: &mut MnaMatrix,
    topo: &CircuitTopology,
    netlist: &Netlist,
    source_scale: f64,
    cap_state: &IndexMap<String, (f64, f64)>,
    ind_state: &IndexMap<String, (f64, f64)>,
) {
    stamp_netlist_in_place(mat, topo, netlist, 0.0, cap_state, ind_state);
    if (source_scale - 1.0).abs() < 1e-15 {
        return;
    }
    let n_nodes = topo.n_nodes();
    for (name, &vi_idx) in &topo.vsrc_index {
        let vi = n_nodes + vi_idx;
        if let Some(Element::VoltageSource { waveform, .. }) = netlist
            .elements
            .iter()
            .find(|e| matches!(e, Element::VoltageSource { name: n, .. } if n == name))
        {
            let v_full = waveform.at(0.0);
            mat.b[vi] = mat.b[vi] - v_full + v_full * source_scale;
        }
    }
    for el in &netlist.elements {
        if let Element::CurrentSource {
            pos, neg, waveform, ..
        } = el
        {
            let i_full = waveform.at(0.0);
            if i_full == 0.0 {
                continue;
            }
            let delta = i_full * (source_scale - 1.0);
            if let Some(&p) = topo.node_index.get(pos) {
                mat.b[p] -= delta;
            }
            if let Some(&n) = topo.node_index.get(neg) {
                mat.b[n] += delta;
            }
        }
    }
}

/// Allocating variant: produces a fresh `MnaMatrix`.  Kept for non-hot
/// call sites (one-off diagnostics, AC side-car G assembly).  The NR
/// inner loops should call [`stamp_netlist_scaled_in_place`] against a
/// reused matrix instead.
pub fn stamp_netlist_scaled(
    topo: &CircuitTopology,
    netlist: &Netlist,
    source_scale: f64,
    cap_state: &IndexMap<String, (f64, f64)>,
    ind_state: &IndexMap<String, (f64, f64)>,
) -> MnaMatrix {
    let mut mat = stamp_netlist(topo, netlist, 0.0, cap_state, ind_state);
    if (source_scale - 1.0).abs() < 1e-15 {
        return mat;
    }
    // Re-scale source contributions: voltage sources stamp into b[vi], current sources into b[node].
    // Rather than re-stamping from scratch, rescale: b[vi] already has waveform.at(0) from
    // stamp_netlist (t=0 = DC value). We just scale b entries for source rows.
    let n_nodes = topo.n_nodes();
    for (name, &vi_idx) in &topo.vsrc_index {
        let vi = n_nodes + vi_idx;
        // Find the source's waveform value and rescale.
        if let Some(Element::VoltageSource { waveform, .. }) = netlist
            .elements
            .iter()
            .find(|e| matches!(e, Element::VoltageSource { name: n, .. } if n == name))
        {
            let v_full = waveform.at(0.0);
            // The stamp put v_full into b[vi]; replace with v_full * source_scale.
            mat.b[vi] = mat.b[vi] - v_full + v_full * source_scale;
        }
    }
    for el in &netlist.elements {
        if let Element::CurrentSource {
            pos, neg, waveform, ..
        } = el
        {
            let i_full = waveform.at(0.0);
            if i_full == 0.0 {
                continue;
            }
            let delta = i_full * (source_scale - 1.0);
            // stamp_current_source: b[pos] -= i, b[neg] += i. Scale correction = delta.
            if let Some(&p) = topo.node_index.get(pos) {
                mat.b[p] -= delta;
            }
            if let Some(&n) = topo.node_index.get(neg) {
                mat.b[n] += delta;
            }
        }
    }
    mat
}

/// In-place stamp.  Clears `mat` then fills the full MNA system.  The
/// caller owns the allocation — used by the NR / transient inner loops
/// to skip per-iteration heap allocation.
pub fn stamp_netlist_in_place(
    mat: &mut MnaMatrix,
    topo: &CircuitTopology,
    netlist: &Netlist,
    t: f64,
    cap_state: &IndexMap<String, (f64, f64)>,
    ind_state: &IndexMap<String, (f64, f64)>,
) {
    mat.clear();
    stamp_netlist_into(mat, topo, netlist, t, cap_state, ind_state);
}

/// Allocating variant: produces a fresh `MnaMatrix`.  Kept for non-hot
/// callers (DC OP one-shots, AC G-matrix assembly, diagnostic dumps).
///
/// `t`           — current simulation time (used for PULSE sources)
/// `cap_state`   — map from capacitor name → (G_eq, I_hist) BE companion pair
/// `ind_state`   — map from inductor name  → (G_eq, I_hist) BE companion pair
pub fn stamp_netlist(
    topo: &CircuitTopology,
    netlist: &Netlist,
    t: f64,
    cap_state: &IndexMap<String, (f64, f64)>,
    ind_state: &IndexMap<String, (f64, f64)>,
) -> MnaMatrix {
    let mut mat = MnaMatrix::new(topo.size);
    stamp_netlist_into(&mut mat, topo, netlist, t, cap_state, ind_state);
    mat
}

/// Internal shared stamping body.  Assumes `mat` is already zeroed at
/// the right size (caller responsibility).
fn stamp_netlist_into(
    mat: &mut MnaMatrix,
    topo: &CircuitTopology,
    netlist: &Netlist,
    t: f64,
    cap_state: &IndexMap<String, (f64, f64)>,
    ind_state: &IndexMap<String, (f64, f64)>,
) {
    use std::collections::HashMap;

    let n_nodes = topo.n_nodes();

    // Build coupled-inductor map: inductor_name → (partner_name, coupling_k)
    // and a value map for inductance lookups.
    let mut coupled_map: HashMap<String, (String, f64)> = HashMap::new();
    let mut ind_values: HashMap<String, f64> = HashMap::new();
    for el in &netlist.elements {
        if let Element::Inductor {
            name, inductance, ..
        } = el
        {
            ind_values.insert(name.clone(), *inductance);
        }
        if let Element::CoupledInductors {
            l1, l2, coupling, ..
        } = el
        {
            coupled_map.insert(l1.clone(), (l2.clone(), *coupling));
            coupled_map.insert(l2.clone(), (l1.clone(), *coupling));
        }
    }

    for el in &netlist.elements {
        match el {
            Element::Resistor {
                pos,
                neg,
                resistance,
                ..
            } => {
                stamp_conductance(&mut mat.a, &topo.node_index, pos, neg, 1.0 / resistance);
            }
            Element::Capacitor { name, pos, neg, .. } => {
                if let Some(&(g_eq, i_hist)) = cap_state.get(name) {
                    stamp_conductance(&mut mat.a, &topo.node_index, pos, neg, g_eq);
                    // BE companion: KCL at pos gives b[pos] += I_hist.
                    // stamp_current_source(neg, pos, v) adds v to b[pos].
                    stamp_current_source(&mut mat.b, &topo.node_index, neg, pos, i_hist);
                }
                // Capacitor absent from cap_state = open circuit (correct for DC OP).
            }
            Element::Inductor { name, pos, neg, .. } => {
                if let Some(&(g_eq, i_hist)) = ind_state.get(name) {
                    // For coupled inductors, skip the standalone self-conductance stamp;
                    // the CoupledInductors arm below handles the full 2×2 companion.
                    if !coupled_map.contains_key(name) {
                        stamp_conductance(&mut mat.a, &topo.node_index, pos, neg, g_eq);
                    }
                    // Always stamp history current source.
                    stamp_current_source(&mut mat.b, &topo.node_index, pos, neg, i_hist);
                }
                // If not in ind_state (no transient yet), inductor = open circuit at DC.
            }
            Element::CoupledInductors {
                l1, l2, coupling, ..
            } => {
                // Both inductors must be in ind_state (transient); skip at DC.
                let Some(&(g_eq1, _)) = ind_state.get(l1) else {
                    continue;
                };
                let Some(&(g_eq2, _)) = ind_state.get(l2) else {
                    continue;
                };
                let Some(&val1) = ind_values.get(l1) else {
                    continue;
                };
                let Some(&val2) = ind_values.get(l2) else {
                    continue;
                };
                let k = *coupling;
                let m = k * (val1 * val2).sqrt();
                let det = val1 * val2 - m * m; // = val1*val2*(1-k²)
                if det.abs() < 1e-40 {
                    continue;
                } // k≈1: degenerate, skip
                  // Extract h from g_eq = h/L  =>  h = g_eq * L
                let h = g_eq1 * val1;
                let g11 = h * val2 / det;
                let g22 = h * val1 / det;
                let g12 = -h * m / det;

                let (pos1, neg1) = find_inductor_terminals(netlist, l1);
                let (pos2, neg2) = find_inductor_terminals(netlist, l2);

                stamp_conductance(&mut mat.a, &topo.node_index, pos1, neg1, g11);
                stamp_conductance(&mut mat.a, &topo.node_index, pos2, neg2, g22);
                stamp_mutual_conductance(&mut mat.a, &topo.node_index, pos1, neg1, pos2, neg2, g12);

                // Verify g_eq2-derived h is consistent (both inductors share same step).
                let _ = g_eq2; // used above implicitly; avoid unused variable warning
            }
            Element::VoltageSource {
                name,
                pos,
                neg,
                waveform,
            } => {
                let vi = n_nodes + topo.vsrc_index[name];
                stamp_vsource(
                    &mut mat.a,
                    &mut mat.b,
                    &topo.node_index,
                    pos,
                    neg,
                    vi,
                    waveform.at(t),
                );
            }
            Element::CurrentSource {
                pos, neg, waveform, ..
            } => {
                // SPICE: current flows from n+ through source to n- → subtract from n+, add to n-.
                stamp_current_source(&mut mat.b, &topo.node_index, pos, neg, waveform.at(t));
            }
            Element::Diode { .. }
            | Element::Mosfet { .. }
            | Element::Bjt { .. }
            | Element::XOsdi { .. }
            | Element::Behavioral { .. }
            | Element::TransmissionLine { .. } => {
                // Stamped by the Device trait inside the Newton-Raphson loop
                // (the T-line carries time-dependent history sources).
            }
        }
    }
}

