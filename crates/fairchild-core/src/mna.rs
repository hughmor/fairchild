/// Modified Nodal Analysis (MNA) matrix assembler.
///
/// Matrix layout (0-based):
///   rows/cols [0 .. n_nodes)          → node voltages (ground excluded)
///   rows/cols [n_nodes .. n_nodes+m)  → voltage-source branch currents
///
/// Ground node "0" is eliminated from the matrix.
use fairchild_parser::{Element, Netlist};
use indexmap::IndexMap;

use crate::error::SimError;

/// The topology/index maps for a circuit — built once, reused across time steps.
///
/// Row layout:
///   `[0 .. n_nodes)`             — circuit node voltages
///   `[n_nodes .. n_nodes+n_vsrc)` — voltage-source branch currents
///   `[n_nodes+n_vsrc .. size)`   — device-internal nodes (e.g. OSDI flow
///                                  branches generated by potential
///                                  contributions in Verilog-A models)
#[derive(Clone)]
pub struct CircuitTopology {
    /// Map from node name → matrix row/col (ground excluded).
    pub node_index: IndexMap<String, usize>,
    /// Map from voltage source name → aux current index within A/b.
    pub vsrc_index: IndexMap<String, usize>,
    /// Total matrix dimension = n_nodes + n_vsources + n_device_extras.
    pub size: usize,
}

impl CircuitTopology {
    pub fn build(netlist: &Netlist) -> CircuitTopology {
        let (node_index, vsrc_index) = index_circuit(netlist);
        let size = node_index.len() + vsrc_index.len();
        CircuitTopology {
            node_index,
            vsrc_index,
            size,
        }
    }

    pub fn n_nodes(&self) -> usize {
        self.node_index.len()
    }

    /// Allocate `n` contiguous MNA rows for device-internal nodes (e.g. OSDI
    /// flow-branch nodes from potential contributions).  Returns the first
    /// allocated index.  Called by `build_devices` once per device that
    /// reports `num_extra_nodes() > 0`.
    pub fn allocate_extra_rows(&mut self, n: usize) -> usize {
        let start = self.size;
        self.size += n;
        start
    }

    /// Retrieve a node voltage from a solution vector.
    pub fn node_voltage(&self, node: &str, x: &[f64]) -> Result<f64, SimError> {
        if node == "0" || node == "gnd" {
            return Ok(0.0);
        }
        self.node_index
            .get(node)
            .map(|&i| x[i])
            .ok_or_else(|| SimError::UnknownNode(node.to_string()))
    }

    /// Retrieve a voltage-source branch current from a solution vector.
    pub fn vsrc_current(&self, vsrc_name: &str, x: &[f64]) -> Result<f64, SimError> {
        self.vsrc_index
            .get(vsrc_name)
            .map(|&i| x[self.n_nodes() + i])
            .ok_or_else(|| SimError::UnknownNode(vsrc_name.to_string()))
    }
}

/// An assembled MNA system: A·x = b.
pub struct MnaMatrix {
    pub a: Vec<Vec<f64>>,
    pub b: Vec<f64>,
}

impl MnaMatrix {
    fn new(size: usize) -> Self {
        MnaMatrix {
            a: vec![vec![0.0f64; size]; size],
            b: vec![0.0f64; size],
        }
    }

    /// Build a zero-filled MnaMatrix at the given dimension.  Useful for
    /// diagnostic passes that need a clean scratch matrix without going
    /// through the netlist stamper.
    pub fn zeros(size: usize) -> Self {
        Self::new(size)
    }

    /// Zero every cell of `a` and every entry of `b` in place.  Used by
    /// the hot NR / transient loops to reuse a single `MnaMatrix`
    /// allocation across iterations instead of paying N+1 heap
    /// allocations per stamp.
    pub fn clear(&mut self) {
        for row in self.a.iter_mut() {
            row.fill(0.0);
        }
        self.b.fill(0.0);
    }
}

