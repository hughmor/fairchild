#!/usr/bin/env python3
"""build_frontend.py — generate the giona front-end netlist and the 8-channel
ring cell it needs.

Writes two decks into `netlists/` (gitignored — they are generated), identical
except for the weight bank and sharing every net name a script would read:

  giona_frontend.sp        64 real add-drop rings with N-doped heaters. VWij is
                           a heater VOLTAGE across 2.2 kOhm, not a weight.
  giona_frontend_idealW.sp the same front end with 8 `fc_optical_2x2` blocks
                           instead, run at w=0 dw_dv=1 so V(Wij) IS the weight
                           in [-1,+1]. For getting an experiment working before
                           the weight-to-voltage map is.

It used to write two. The other was `mrm_wdm8.sp`, an 8-channel add-drop PCell
spelled out wire by wire because a subckt body cannot declare `.optical_port`
and one physical ring has to serve all eight wavelengths off one junction —
several hundred port names, hence a generator. Both Verilog-A rings this file
now instantiates are bundle-aware, so the deck says `.optical_port bus 8` and
the model is compiled at that width. The generator for the generator is gone.

Two ring models, because the chip has two kinds of ring:

  mrm_addrop.va    the 8 modulators — PN junction, depletion and injection
                   through one carrier population, calibrated against the May
                   capture. 300 nm coupler gaps.
  ring_nheater.va  the 64 weight rings — no junction, tuned by an N-doped
                   resistor in the waveguide. 200 nm coupler gaps, so a
                   stronger coupling: kappa_L 0.387 against the modulator's
                   0.183, scaled by the FEM's gap ratio.

Run:  .venv/bin/python experiments/giona/build_frontend.py
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
OUT = HERE / "netlists"
PCELLS = REPO / "examples" / "photonic" / "pcells"

N_CH = 8
# Source-bank default grid (100 GHz spacing) — ring i is trimmed to LAMBDAS[i].
LAMBDAS_NM = [1546.12, 1546.92, 1547.72, 1548.51,
              1549.32, 1550.12, 1550.92, 1551.72]
RADIUS_M = 8e-6
N_G = 4.2
WL_REF_NM = 1550.0
# The two Verilog-A rings this front end is built from. Both are bundle-aware,
# so ONE instance carries all eight channels off one junction or one heater —
# which is why the hand-generated 8-channel subckt this file used to emit is
# gone. A subckt body cannot declare `.optical_port`, so its wide ports had to
# be spelled out wire by wire; a bundle model has no such problem.
VA_MRM = REPO / "examples" / "verilog_a" / "models" / "mrm_addrop.va"
VA_WEIGHT = REPO / "examples" / "verilog_a" / "models" / "ring_nheater.va"


# ── per-ring trim ────────────────────────────────────────────────────────────
def n_eff_for(target_nm: float, guess: float = 2.2810, n_g: float = N_G) -> float:
    """The `n_eff` that puts a resonance at `target_nm`. Closed form.

    This used to scan 121 candidate indices through a full ring simulation per
    ring, because the segment adds first-order dispersion and the naive comb
    formula misses. The dispersion is a straight line, so the comb formula does
    not have to miss — carry it through:

        n_eff(lam)*L = m*lam,  n_eff(lam) = n0 + (lam - ref)*(n0 - n_g)/ref
        =>  n0 = m*ref/L + n_g*(lam - ref)/lam

    with `m` the order nearest the target. Exact, and 72 rings now cost 72
    arithmetic expressions instead of 8 712 solves.
    """
    L = 2.0 * math.pi * RADIUS_M
    m = round(guess * L / (target_nm * 1e-9))
    return m * (WL_REF_NM * 1e-9) / L + n_g * (target_nm - WL_REF_NM) / target_nm


# ── the front end ────────────────────────────────────────────────────────────
def frontend(trims: list[float], wtrims: list[float], real_weights: bool) -> str:
    L: list[str] = []
    add = L.append

    add("* giona_frontend.sp — GENERATED by experiments/giona/build_frontend.py.")
    add("* Do not edit; edit the generator.")
    add("*")
    add("* Front-end of the giona neuron chip: WDM source bank -> cascaded ring")
    add("* weight bank -> long bus waveguide -> 1:1 tap -> 1:8 log tree -> eight")
    add("* programmable 2x2 weight blocks (64 weights).")
    add("*")
    add("*   source_bank (8 lasers + 8 MZMs + mux)")
    add("*        | 8-channel bus")
    add("*        v")
    add("*   [ring 1] -- [ring 2] -- ... -- [ring 8]      shared BUS waveguide")
    add("*      ^  |        ^  |               ^  |")
    add("*      |  v        |  v               |  v")
    add("*   drp_out <---- add/drop bus runs the other way <---- (dark)")
    add("*        |")
    add("*        (ring 8 thru) --> 2 mm waveguide --> Y tap")
    add("*                                             |     \\")
    add("*                                      tap_out       1:8 log tree")
    add("*                                                      | x8")
    add("*                                              Xw1..Xw8 (fc_optical_2x2)")
    add("*")
    add("* Weights: net Wij is the weight of wavelength channel j in block i, set")
    add("* by voltage source VWij. The blocks run w=0 dw_dv=1, so the weight IS")
    add("* the volt value, clamped to [-1, +1], with P_drop - P_thru = w * P_in")
    add("* (what a balanced photodetector pair reads).")
    add("*")
    add("* Readout ports: tap_out (the 1:1 tap), drp_out (the drop bus), and")
    add("* wthru<i> / wdrop<i> for each weight block.")
    add("*")
    add("* Analysis is a bare .op so the file runs as-is; drive it from Python")
    add("* (set_param / set_source) for sweeps and transients. For transients,")
    add("* note the 2 mm waveguide's group delay is 28 ps and only appears with")
    add("* `waveguide_delay=1` plus a timestep below it.")
    add("")
    add(f".include {PCELLS / 'source_bank.sp'}")
    add(f".va {VA_MRM}")
    add(f".va {VA_WEIGHT}")
    add("")
    add("* ── geometry knobs ─────────────────────────────────────────────────")
    add(".param pitch=100e-6      * bus waveguide between adjacent rings (m)")
    add(".param l_out=2e-3        * long output waveguide (m)")
    add(".param wg_loss=2.0       * waveguide loss (dB/cm)")
    add(".param n_g=4.2")
    add(".param radius=8e-6")
    add(".param kappa_l=0.183     * modulator rings, 300 nm coupler gaps")
    add(".param kappa_w=0.2510    * weight rings, set by their Q of 5900")
    add(".param n_g_w=3.98        * weight rings, set by their 12.1 nm FSR")
    add("")

    # ── optical buses. Every one is an 8-channel bundle. ────────────────────
    add("* ── optical nets (every port is an 8-channel bundle) ───────────────")
    ports = ["src"]
    for i in range(1, N_CH + 1):
        ports += [f"bin{i}", f"bout{i}", f"ain{i}", f"dout{i}"]
    ports += ["wg_out", "tap_out", "tree_in"]
    ports += ["l1a", "l1b", "l2a", "l2b", "l2c", "l2d"]
    for i in range(1, N_CH + 1):
        ports += [f"win{i}", f"dark{i}", f"wthru{i}", f"wdrop{i}"]
        # Internal hops of bank i's bus and drop cascades.
        ports += [f"wb{i}_{j}" for j in range(2, N_CH + 1)]
        ports += [f"wd{i}_{j}" for j in range(2, N_CH + 1)]
    for p in ports:
        add(f".optical_port {p} {N_CH}")
    add("")

    # ── stimulus ───────────────────────────────────────────────────────────
    add("* ── source bank: 8 lasers, each through its own ideal MZM, muxed ───")
    add("* One instance carries the whole bus (33 ports = 24 bus wires + 8")
    add("* drives + return). Drive 0 V = fully ON, v_pi = off.")
    add("Xsrc src " + " ".join(f"d{k}" for k in range(1, N_CH + 1))
        + " 0 source_bank")
    for k in range(1, N_CH + 1):
        add(f"Vd{k} d{k} 0 DC 0")
    add("")
    add("* Source into the first ring.")
    add("Xwg_in src bin1 fc_waveguide l_m={pitch} n_g={n_g}"
        " alpha_dB_cm={wg_loss}")
    add("")

    # ── ring bank ──────────────────────────────────────────────────────────
    add("* ── ring weight bank: 8 rings sharing the bus AND the add/drop bus ─")
    add("* Bus runs 1->8 (thru of i feeds in of i+1). The add/drop bus runs the")
    add("* other way (drop of i+1 feeds add of i), so drp_out collects at ring 1")
    add("* and ring 8's add port is the dark end.")
    add("* n_eff is trimmed per ring so ring i sits on channel i; it cannot be")
    add("* derived from m*lambda = n_eff*L because the segment adds dispersion")
    add("* toward n_g (the generator finds it numerically).")
    for i in range(1, N_CH + 1):
        add(f"* ring {i} — channel {i - 1}, lambda = {LAMBDAS_NM[i - 1]:.2f} nm")
        add(f"Xr{i} bin{i} bout{i} ain{i} dout{i} pn{i} 0 ht{i} 0 trm{i}"
            f" mrm_addrop radius={{radius}} kappa_l={{kappa_l}}"
            f" n_eff={trims[i - 1]:.9f}")
        add(f"Vpn{i} pn{i} 0 DC 0")
        add(f"Iht{i} 0 ht{i} DC 0")
        # Each ring's own path to ambient. Tie two `trm` nodes together, or put
        # a resistor between them, and those two rings are thermally coupled —
        # the model exposes `th` so a deck can say so.
        if i < N_CH:
            add(f"Xwb{i} bout{i} bin{i + 1} fc_waveguide l_m={{pitch}}"
                f" n_g={{n_g}} alpha_dB_cm={{wg_loss}}")
            add(f"Xwd{i} dout{i + 1} ain{i} fc_waveguide l_m={{pitch}}"
                f" n_g={{n_g}} alpha_dB_cm={{wg_loss}}")
    add("")
    add(f"* Dark end of the add/drop bus: ain{N_CH} is left undriven. It used to")
    add("* carry a zero-power laser, which relied on one scalar line replicating")
    add("* across all 8 channels — the parser refuses that now, and it was never")
    add("* needed: gmin floors the undriven re/im wires at zero, and the drop")
    add("* coupler takes its wavelength tag from the lit ring side.")
    add(f"* drop-bus readout is dout1; bus output is bout{N_CH}.")
    add("")

    # ── output waveguide + tap + log tree ──────────────────────────────────
    add("* ── 2 mm output waveguide ─────────────────────────────────────────")
    add(f"Xwg_out bout{N_CH} wg_out fc_waveguide l_m={{l_out}} n_g={{n_g}}"
        " alpha_dB_cm={wg_loss}")
    add("")
    add("* ── Y tap: one output is the readout, the other feeds the log tree ─")
    add("* fc_splitter is a 3 dB Y-branch: each output gets a/sqrt(2).")
    add("Xtap wg_out tap_out tree_in fc_splitter")
    add("")
    add("* ── 1:8 log tree, 3 stages of Y-branches (7 splitters, -9.03 dB) ──")
    add("Xt1  tree_in l1a l1b fc_splitter")
    add("Xt2a l1a l2a l2b fc_splitter")
    add("Xt2b l1b l2c l2d fc_splitter")
    for j, (src, a, b) in enumerate(
        [("l2a", "win1", "win2"), ("l2b", "win3", "win4"),
         ("l2c", "win5", "win6"), ("l2d", "win7", "win8")], start=1
    ):
        add(f"Xt3{'abcd'[j - 1]} {src} {a} {b} fc_splitter")
    add("")

    # ── weight blocks ──────────────────────────────────────────────────────
    if not real_weights:
        add("* ── 8 programmable 2x2 weight blocks, 8 weights each = 64 ──────────")
        add("* IDEAL weights: w=0 dw_dv=1 makes V(Wij) the weight directly,")
        add("* clamped to [-1,+1], with P_drop - P_thru = w * P_in. No rings, no")
        add("* heaters, no thermal crosstalk, no mapping to configure.")
        add("*")
        add("* This deck exists so an experiment can be got working before the")
        add("* weight-to-voltage map is. Its sibling giona_frontend.sp has the 64")
        add("* real rings; the two share every other net name, so a script can")
        add("* swap decks and keep its readouts.")
        for i in range(1, N_CH + 1):
            ctl = " ".join(f"W{i}{j}" for j in range(1, N_CH + 1))
            add(f"Xw{i} win{i} dark{i} wthru{i} wdrop{i} {ctl} 0 fc_optical_2x2"
                f" w=0 dw_dv=1")
            for j in range(1, N_CH + 1):
                add(f"VW{i}{j} W{i}{j} 0 DC 0")
        add("")
        add(".op")
        add(".end")
        return "\n".join(L) + "\n"

    add("* ── 8 weight banks of 8 add-drop rings each = 64 physical rings ──")
    add("* Each bank is a cascade on one bus, ring j trimmed onto channel j, so")
    add("* ring (i,j) weights wavelength j in block i. They are ring_nheater:")
    add("* no junction, tuned by an N-doped resistor in the waveguide itself.")
    add("*")
    add("* THE CONTROL IS A HEATER VOLTAGE, NOT A WEIGHT. The old fc_optical_2x2")
    add("* blocks ran w=0 dw_dv=1 so V(Wij) WAS the weight, clamped to [-1,1].")
    add("* A real ring has no such affordance: VWij drives 2.2 kOhm, tunes the")
    add("* ring through resonance, and the weight is where that lands the")
    add("* channel between thru and drop. Zero volts is not zero weight.")
    for i in range(1, N_CH + 1):
        add(f"* ── bank {i} ──")
        for j in range(1, N_CH + 1):
            b_in = f"win{i}" if j == 1 else f"wb{i}_{j}"
            b_out = f"wthru{i}" if j == N_CH else f"wb{i}_{j + 1}"
            # The drop bus runs the other way, as it does in the ring bank
            # above: ring j's drop feeds ring j-1's add, so bank i's drop
            # collects at ring 1 and ring N's add port is the dark end.
            d_out = f"wdrop{i}" if j == 1 else f"wd{i}_{j}"
            d_in = f"dark{i}" if j == N_CH else f"wd{i}_{j + 1}"
            add(f"Xw{i}_{j} {b_in} {b_out} {d_in} {d_out} hw{i}_{j} 0 tw{i}_{j}"
                f" ring_nheater radius={{radius}} kappa_l={{kappa_w}}"
                f" n_g={{n_g_w}} n_eff={wtrims[j - 1]:.9f}")
            add(f"VW{i}{j} hw{i}_{j} 0 DC 0")
    add("")
    add(".op")
    add(".end")
    return "\n".join(L) + "\n"


# ── per-ring n_eff trim ──────────────────────────────────────────────────────
def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    print("trimming rings onto their channels …")
    trims = [n_eff_for(wl) for wl in LAMBDAS_NM]
    # The weight rings have their own group index, so their trim does too.
    wtrims = [n_eff_for(wl, n_g=3.98) for wl in LAMBDAS_NM]
    for wl, ne in zip(LAMBDAS_NM, trims):
        print(f"  {wl:.2f} nm → n_eff = {ne:.9f}")

    decks = []
    for name, real in (("giona_frontend.sp", True),
                       ("giona_frontend_idealW.sp", False)):
        d = OUT / name
        d.write_text(frontend(trims, wtrims, real))
        print(f"wrote {d}")
        decks.append(d)
    deck = decks[0]

    # Smoke check: both must parse, expand and converge.
    import fairchild as fc
    ideal = fc.Circuit()
    ideal.load(str(decks[1]))
    ideal.run("op")
    print(f"\n{decks[1].name}: parses and converges")
    c = fc.Circuit()
    c.load(str(deck))
    r = c.run("op")

    def p(port: str, k: int) -> float:
        return (float(r[f"V({port}_re_{k})"][0]) ** 2
                + float(r[f"V({port}_im_{k})"][0]) ** 2) / 1e-3

    print("\nDC operating point (all weights 0, all rings unbiased):")
    print("  ch   tap_out    drp_out    wthru1     wdrop1")
    for k in range(N_CH):
        print(f"  {k}  {p('tap_out', k):9.5f}  {p('dout1', k):9.5f}  "
              f"{p('wthru1', k):9.5f}  {p('wdrop1', k):9.5f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
