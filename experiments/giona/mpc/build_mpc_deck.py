#!/usr/bin/env python3
"""build_mpc_deck.py — the 8x8 recurrent network, wired for MPC.

Emits two decks into `netlists/`, identical in every net name and differing
only in what a weight is made of:

  giona_mpc_idealW.sp   `fc_optical_2x2` blocks at w=0 dw_dv=1, so V(Wij) IS the
                        weight in [-1,+1]. Prove the loop closes here first.
  giona_mpc.sp          the same topology with 64 `ring_nheater` rings, where
                        VWij is a heater VOLTAGE and the weight is wherever that
                        lands the ring.

── The wavelength budget ────────────────────────────────────────────────────

The hardware is unchanged: 8 wavelengths, 8 modulator rings, 8 weight banks of
8 rings. What changes is the ALLOCATION, which is a programming choice:

  lambda 1..6   neurons.  Ring i is driven by bank i's balanced photodiode, so
                its channel carries that neuron's state and the loop is closed.
  lambda 7,8    inputs.   Modulated OFF-CHIP at the source MZM. Rings 7 and 8
                are parked off resonance so their channels pass the modulator
                bank untouched and reach the weight banks at full amplitude.

Two input channels and not one, because the MPC input is q = 2*Theta^T*Psi*x_k
and that map has RANK 2 for a two-state plant. One channel could only deliver a
rank-1 input; an unweighted ninth wavelength would be worse still, since it hits
every bank's thru port with the same weight and can only carry a term common to
every neuron.

So the programmed matrix is 6x8: [ W_recurrent (6x6) | W_input (6x2) ], which is
48 of the 64 rings. Banks 7 and 8 exist and are simply not read.

── Two things this deck does NOT do ─────────────────────────────────────────

It does not trim the rings and it does not solve the biases. Both are per-run
and both belong to the driver, because `rnn_math.md` §9 is emphatic that an
untrimmed ring has |G| ~ 0.24-1.0 with the OPPOSITE SIGN to a trimmed one, and
the deck has no business baking in a number that decides that.

Run:  .venv/bin/python experiments/giona/mpc/build_mpc_deck.py
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent      # this experiment's own directory
GIONA = HERE.parent                         # experiments/giona
REPO = GIONA.parents[1]                     # repo root
OUT = HERE / "netlists"
PCELLS = REPO / "examples" / "photonic" / "pcells"
VA_MRM = REPO / "examples" / "verilog_a" / "models" / "mrm_addrop.va"
VA_WEIGHT = REPO / "examples" / "verilog_a" / "models" / "ring_nheater.va"
NEURON = GIONA / "common" / "netlists" / "neuron_junction_wdm8.sp"

N_CH = 8            # wavelengths, rings, banks — the hardware
N_NEURON = 6        # lambda 1..6
N_INPUT = 2         # lambda 7,8
LAMBDAS_NM = [1546.12, 1546.92, 1547.72, 1548.51,
              1549.32, 1550.12, 1550.92, 1551.72]
RADIUS_M = 8e-6
N_G_MOD, N_G_W = 4.2, 3.98
WL_REF_NM = 1550.0


def n_eff_for(target_nm: float, n_g: float, guess: float = 2.2810) -> float:
    """The `n_eff` that puts a resonance at `target_nm`. Closed form.

    n_eff(lam)*L = m*lam with n_eff(lam) = n0 + (lam-ref)*(n0-n_g)/ref gives
    n0 = m*ref/L + n_g*(lam-ref)/lam, with m the order nearest the target.
    """
    import math
    L = 2.0 * math.pi * RADIUS_M
    m = round(guess * L / (target_nm * 1e-9))
    return m * (WL_REF_NM * 1e-9) / L + n_g * (target_nm - WL_REF_NM) / target_nm


def deck(real_weights: bool) -> str:
    L: list[str] = []
    add = L.append
    kind = "64 ring_nheater rings" if real_weights else "8 ideal fc_optical_2x2 blocks"
    add(f"* giona_mpc{'' if real_weights else '_idealW'}.sp — GENERATED by")
    add("* experiments/giona/mpc/build_mpc_deck.py. Do not edit; edit the generator.")
    add("*")
    add(f"* The 8x8 recurrent network with {kind}.")
    add(f"* lambda 1..{N_NEURON} are neurons (ring driven by its bank's balanced PD);")
    add(f"* lambda {N_NEURON + 1},{N_CH} are inputs, modulated off-chip at the source MZM")
    add("* and passed through by rings parked off resonance.")
    add("*")
    add("* Knobs the driver sets, and nothing else:")
    add("*   Vd<k>      source MZM drive. 0 = fully on. Inputs sit at v_pi/2 and")
    add("*              swing bipolar about it.")
    add("*   Iht<i>     modulator ring heater. TRIM. Also what parks rings 7,8.")
    add("*   PDB<i>     neuron bias, so the rest point is where the driver wants it.")
    add("*   VW<i><j>   weight (ideal deck) or heater volts (ring deck).")
    add("*")
    add("* Readouts: I(Vsen<i>) is neuron i's state — the junction current, which")
    add("* is what the recurrence calls y_i — with mc<i> the cathode voltage it")
    add("* develops, plus the optical bus.")
    add("")
    add(f".include {PCELLS / 'source_bank.sp'}")
    add(f".include {NEURON}")
    add(f".va {VA_MRM}")
    if real_weights:
        add(f".va {VA_WEIGHT}")
    add("")
    add(".param pitch=533e-6      * bus waveguide between adjacent rings (m)")
    add(".param l_out=2e-3        * long output waveguide (m)")
    add(".param wg_loss=2.0       * waveguide loss (dB/cm)")
    add(".param radius=8e-6")
    add(".param kappa_l=0.183     * modulator rings, 300 nm coupler gaps")
    add(".param kappa_w=0.2510    * weight rings, set by their Q of 5900")
    add(".param p_las=30          * laser power per channel (mW)")
    add(".param v_pi=1.0          * source MZM v_pi")
    add("")

    # ── optical nets ────────────────────────────────────────────────────────
    ports = ["src"]
    for i in range(1, N_CH + 1):
        ports += [f"bin{i}", f"bout{i}", f"ain{i}", f"dout{i}"]
    ports += ["wg_out", "tap_out", "tree_in", "l1a", "l1b", "l2a", "l2b", "l2c", "l2d"]
    for i in range(1, N_CH + 1):
        ports += [f"win{i}", f"dark{i}", f"wthru{i}", f"wdrop{i}"]
        if real_weights:
            ports += [f"wb{i}_{j}" for j in range(2, N_CH + 1)]
            ports += [f"wd{i}_{j}" for j in range(2, N_CH + 1)]
    add("* ── optical nets (every port is an 8-channel bundle) ───────────────")
    for p in ports:
        add(f".optical_port {p} {N_CH}")
    add("")

    # ── source bank ─────────────────────────────────────────────────────────
    add("* ── source bank: 8 CW lasers, each through its own ideal MZM ───────")
    add("* Neuron channels sit fully on (Vd=0) and are modulated by their ring.")
    add("* Input channels sit at quadrature so the drive is linear and bipolar.")
    wl = " ".join(f"wl{k + 1}={LAMBDAS_NM[k]:.2f}" for k in range(N_CH))
    pw = " ".join(f"p{k + 1}={{p_las}}" for k in range(N_CH))
    add("Xsrc src " + " ".join(f"d{k}" for k in range(1, N_CH + 1))
        + f" 0 source_bank {wl} {pw} v_pi={{v_pi}}")
    for k in range(1, N_CH + 1):
        init = "0" if k <= N_NEURON else "{v_pi/2}"
        tag = "neuron, fully on" if k <= N_NEURON else "INPUT, quadrature"
        add(f"Vd{k} d{k} 0 DC {init}      * {tag}")
    add("")
    add("Xwg_in src bin1 fc_waveguide l_m={pitch} n_g=4.2 alpha_dB_cm={wg_loss}")
    add("")

    # ── modulator ring bank ─────────────────────────────────────────────────
    add("* ── modulator bank: 8 add-drop rings on a shared bus ──────────────")
    add("* Rings 1..6 are the neurons: anode grounded, cathode driven by the")
    add("* neuron junction, so the junction current IS the state. Rings 7,8 have")
    add("* no junction drive and get parked off resonance by their heaters.")
    for i in range(1, N_CH + 1):
        ne = n_eff_for(LAMBDAS_NM[i - 1], N_G_MOD)
        role = "neuron" if i <= N_NEURON else "INPUT passthrough — park off resonance"
        cath = f"mc{i}" if i <= N_NEURON else "0"
        add(f"* ring {i} — lambda {LAMBDAS_NM[i - 1]:.2f} nm, {role}")
        # A 0 V source in series with the anode, so the junction current is a
        # branch unknown that can be READ. Inferring it from the cathode voltage
        # through the diode law works but needs the voltage to a part in 1e6,
        # which is below the solver's reltol on a node sitting near a volt.
        add(f"Vsen{i} 0 an{i} DC 0")
        add(f"Xr{i} bin{i} bout{i} ain{i} dout{i} an{i} {cath} ht{i} 0 trm{i}"
            f" mrm_addrop radius={{radius}} kappa_l={{kappa_l}} n_eff={ne:.9f}")
        add(f"Iht{i} 0 ht{i} DC 0")
        if i < N_CH:
            add(f"Xwb{i} bout{i} bin{i + 1} fc_waveguide l_m={{pitch}} n_g=4.2"
                f" alpha_dB_cm={{wg_loss}}")
            add(f"Xwd{i} dout{i + 1} ain{i} fc_waveguide l_m={{pitch}} n_g=4.2"
                f" alpha_dB_cm={{wg_loss}}")
    add("")

    # ── bus out, tap, tree ──────────────────────────────────────────────────
    add("* ── output bus, 1:1 tap, 1:8 log tree ─────────────────────────────")
    add(f"Xwg_out bout{N_CH} wg_out fc_waveguide l_m={{l_out}} n_g=4.2"
        " alpha_dB_cm={wg_loss}")
    add("Xtap wg_out tap_out tree_in fc_splitter")
    add("Xt1  tree_in l1a l1b fc_splitter")
    add("Xt2a l1a l2a l2b fc_splitter")
    add("Xt2b l1b l2c l2d fc_splitter")
    for j, (s, a, b) in enumerate(
        [("l2a", "win1", "win2"), ("l2b", "win3", "win4"),
         ("l2c", "win5", "win6"), ("l2d", "win7", "win8")], start=1
    ):
        add(f"Xt3{'abcd'[j - 1]} {s} {a} {b} fc_splitter")
    add("")

    # ── weight banks ────────────────────────────────────────────────────────
    add(f"* ── 8 weight banks ({kind}) ──")
    add("* Bank i weights every channel j. Banks 1..6 feed neurons; 7,8 are")
    add("* instantiated because the hardware has them, and simply not read.")
    for i in range(1, N_CH + 1):
        if real_weights:
            add(f"* ── bank {i} ──")
            for j in range(1, N_CH + 1):
                ne = n_eff_for(LAMBDAS_NM[j - 1], N_G_W)
                b_in = f"win{i}" if j == 1 else f"wb{i}_{j}"
                b_out = f"wthru{i}" if j == N_CH else f"wb{i}_{j + 1}"
                d_out = f"wdrop{i}" if j == 1 else f"wd{i}_{j}"
                d_in = f"dark{i}" if j == N_CH else f"wd{i}_{j + 1}"
                add(f"Xw{i}_{j} {b_in} {b_out} {d_in} {d_out} hw{i}_{j} 0 tw{i}_{j}"
                    f" ring_nheater radius={{radius}} kappa_l={{kappa_w}}"
                    f" n_g={N_G_W} n_eff={ne:.9f}")
                add(f"VW{i}{j} hw{i}_{j} 0 DC 0")
        else:
            ctl = " ".join(f"W{i}{j}" for j in range(1, N_CH + 1))
            add(f"Xw{i} win{i} dark{i} wthru{i} wdrop{i} {ctl} 0 fc_optical_2x2"
                f" w=0 dw_dv=1")
            for j in range(1, N_CH + 1):
                add(f"VW{i}{j} W{i}{j} 0 DC 0")
    add("")

    # ── neurons ─────────────────────────────────────────────────────────────
    add("* ── the O/E/O neurons: bank i's balanced PD drives ring i ─────────")
    for i in range(1, N_NEURON + 1):
        add(f"Xj{i} wthru{i} wdrop{i} bp{i} bn{i} bc{i} mc{i} 0"
            f" neuron_junction_wdm8 c_j=10f r_sh=17e3 r_series=1")
        add(f"Vbp{i} bp{i} 0 DC 3")
        add(f"Vbn{i} bn{i} 0 DC -3")
        add(f"Vpdb{i} bc{i} 0 DC 0        * PDB{i}: neuron bias")
    add("")
    add(".op")
    add(".end")
    return "\n".join(L) + "\n"


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    made = []
    for name, real in (("giona_mpc_idealW.sp", False), ("giona_mpc.sp", True)):
        p = OUT / name
        p.write_text(deck(real))
        print(f"wrote {p}")
        made.append(p)

    import fairchild as fc
    for p in made:
        c = fc.Circuit()
        c.load(str(p))
        r = c.run("op")
        mc = [float(r[f"V(mc{i})"][0]) for i in range(1, N_NEURON + 1)]
        print(f"  {p.name}: converges; mc = "
              + " ".join(f"{v * 1e3:+.3f}mV" for v in mc))
    return 0


if __name__ == "__main__":
    sys.exit(main())
